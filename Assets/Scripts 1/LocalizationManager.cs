    public string Get(string key)
    {
        if (languages.ContainsKey(currentLanguage))
        {
            if (languages[currentLanguage].ContainsKey(key))
            {
                return languages[currentLanguage][key];
            }
        }
        // Fallback to English
        if (languages["English"].ContainsKey(key))
        {
            return languages["English"][key];
        }
        return key; // Fallback to key itself
    }
    
    // Format string helper
    public string GetFormat(string key, params object[] args)
    {
        string val = Get(key);
        try { return string.Format(val, args); }
        catch { return val; } 
    }

    public delegate void LanguageChangeHandler();
    public event LanguageChangeHandler OnLanguageChanged;

    public void SetLanguage(string lang)
    {
        if (languages.ContainsKey(lang))
        {
            currentLanguage = lang;
            PlayerPrefs.SetString("SelectedLanguage", lang);
            PlayerPrefs.Save();
            OnLanguageChanged?.Invoke(); // Trigger event
        }
    }
    
    public string GetCurrentLanguage() { return currentLanguage; }

    public string GetForLanguage(string lang, string key)
    {
        if (languages.ContainsKey(lang) && languages[lang].ContainsKey(key))
        {
            return languages[lang][key];
        }
        return Get(key);
    }
