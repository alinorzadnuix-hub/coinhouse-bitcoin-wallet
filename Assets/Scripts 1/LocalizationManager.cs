    /// <summary>
    /// Strips or sanitizes icons for UI text display if needed, or returns the text.
    /// </summary>
    public static string CleanIcons(string text)
    {
        if (string.IsNullOrEmpty(text)) return "";
        return text;
    }
    private static LocalizationManager _instance;

    public static LocalizationManager Instance
    {
        get
        {
            if (_instance == null)
            {
                _instance = FindAnyObjectByType<LocalizationManager>();
                if (_instance == null)
                {
                    GameObject obj = new GameObject("LocalizationManager");
                    _instance = obj.AddComponent<LocalizationManager>();
                }
            }
            return _instance;
        }
    }

    private Dictionary<string, Dictionary<string, string>> languages = new Dictionary<string, Dictionary<string, string>>();
    private string currentLanguage = "English";

    void Awake()
    {
        if (_instance == null)
        {
            _instance = this;
            DontDestroyOnLoad(gameObject);
            Init();
        }
        else if (_instance != this)
        {
            Destroy(gameObject);
        }
    }

